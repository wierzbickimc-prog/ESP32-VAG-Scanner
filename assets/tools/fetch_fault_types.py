"""Download the KW1281 fault type list and write kwcore/fault_types.h.

The list (status byte bits 0-6 -> "Short to Ground" etc.) comes from
KLineKWP1281Lib_ESP32 by domnulvlad, which is GPL-3.0, so the generated header
is gitignored like the Ross-Tech CSV. Without it the apps show the number only.

Run:  python3 fetch_fault_types.py
"""
import os, re, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "kwcore", "fault_types.h")
REPO = "domnulvlad/KLineKWP1281Lib_ESP32"
COMMIT = "dfd5ae72001da1831a7d6207fb9c2aa573b8c918"
URL = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/src/fault_code_elaboration_EN.h"
UA = {"User-Agent": "esp32-vag-scanner/1.0"}


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src = urllib.request.urlopen(urllib.request.Request(URL, headers=UA), timeout=60).read().decode()
    types = {int(code, 16): text for code, text in
             re.findall(r'KWP_ELAB_([0-9A-F]{2})\[\]\s*(?:PROGMEM\s*)?=\s*"((?:[^"\\]|\\.)*)"', src)}
    if len(types) < 64 or types.get(0x1D) != "Short to Ground":
        raise SystemExit(f"unexpected source format ({len(types)} entries); not writing {OUT}")

    lines = [
        "/* Generated by assets/tools/fetch_fault_types.py; do not edit. */",
        f"/* Source: {URL} (GPL-3.0) */",
        "static const char *const kw_fault_type_names[] = {",
    ]
    lines += [f"    [0x{code:02X}] = {c_string(text)}," for code, text in sorted(types.items())]
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(types)} fault types to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
